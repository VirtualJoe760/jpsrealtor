const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = 'F:/web-clients/joseph-sardella/jpsrealtor/src/lib/dialer/queue-pagination.ts';
const fixture = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module: fixture, exports: fixture.exports });
const { paginateQueue } = fixture.exports;
const contacts = Array.from({ length: 208 }, (_, index) => ({ id: index + 1 }));
const visited = Array.from({ length: 21 }, (_, page) => paginateQueue(contacts, page).items).flat();
assert.equal(visited.length, 208);
assert.equal(new Set(visited.map(contact => contact.id)).size, 208, 'Every queue contact must be reachable exactly once');
assert.equal(visited[207].id, 208);
assert.equal(paginateQueue(contacts, 999).items.length, 8);
assert.equal(paginateQueue(contacts, -1).start, 1);
const filtered = contacts.filter(contact => contact.id > 190);
assert.equal(paginateQueue(filtered, 0).start, 1);
assert.equal(paginateQueue(filtered, 1).items[7].id, 208, 'Search results must paginate beyond their first page');
assert.equal(paginateQueue([], 9).page, 0);
assert.equal(paginateQueue([], 9).start, 0);
assert.equal(paginateQueue([], 9).end, 0);
assert.throws(() => paginateQueue(contacts, 0, 0));
console.log('PASS: all 208 contacts reachable once, final page, empty queue, filtered pages and bounds.');
